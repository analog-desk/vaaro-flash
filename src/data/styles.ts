import type { FlashDirection, Modifier, StyleId } from './types';

export interface StylePreset {
  id: StyleId;
  label: string;
  short: string;
  /**
   * Exposure bias on the subject, in stops, before film limits are applied.
   * The engine clamps this per film type (slide film tolerates very little).
   */
  subjectBias: number;
  /** When flash is the main light: background ambient relative to correct (stops). */
  backgroundOffset: number;
  /** When flash is fill: flash relative to ambient (stops). */
  fillOffset: number;
  /** Allows slower shutter (motion blur / ghosting) when flash freezes the subject. */
  allowDrag: boolean;
  preferredModifier: Modifier;
  preferredDirection: FlashDirection;
  /** Prefer hard (bare, direct) light? */
  hardLight: boolean;
  /** Film tags that suit this look; used to suggest stocks. */
  filmTags: string[];
  /** Fujifilm film simulation that approximates the look on the X-T5. */
  fujiSimulation: string;
  how: {
    aperture: string;
    shutter: string;
    flash: string;
    ambient: string;
    colour: string;
    shadows: string;
    extra: string;
  };
}

